-- Daily sales each center manager reports: BookMyShow, the Maaya World website and the cash counter.
-- One row per center per day; sending the form again for the same day corrects that row.

CREATE TABLE public.daily_collections (
    id bigint NOT NULL,
    location_id integer NOT NULL,
    collection_date date NOT NULL,
    book_my_show double precision NOT NULL DEFAULT 0,
    website double precision NOT NULL DEFAULT 0,
    cash_counter double precision NOT NULL DEFAULT 0,
    submitted_by_id bigint,
    submitted_by_name character varying(255),
    submitted_at timestamp(6) without time zone NOT NULL,
    updated_at timestamp(6) without time zone
);

ALTER TABLE public.daily_collections ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.daily_collections_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.daily_collections
    ADD CONSTRAINT daily_collections_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.daily_collections
    ADD CONSTRAINT uq_daily_collections_center_day UNIQUE (location_id, collection_date);

ALTER TABLE ONLY public.daily_collections
    ADD CONSTRAINT fk_daily_collections_location FOREIGN KEY (location_id) REFERENCES public.locations(location_id);

-- Who sent it; kept if that person is later deleted
ALTER TABLE ONLY public.daily_collections
    ADD CONSTRAINT fk_daily_collections_submitted_by FOREIGN KEY (submitted_by_id) REFERENCES public.employees(id) ON DELETE SET NULL;

ALTER TABLE public.daily_collections
    ADD CONSTRAINT ck_daily_collections_amounts CHECK (book_my_show >= 0 AND website >= 0 AND cash_counter >= 0);

CREATE INDEX idx_daily_collections_date ON public.daily_collections (collection_date);
