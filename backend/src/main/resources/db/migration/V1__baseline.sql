-- ---------------------------------------------------------------------------------------------
-- How the tables connect
-- ---------------------------------------------------------------------------------------------

-- Every center is a row in locations; staff and payroll runs point at a center.
ALTER TABLE ONLY public.employees
    ADD CONSTRAINT fk_employees_location FOREIGN KEY (location_id) REFERENCES public.locations(location_id);
ALTER TABLE ONLY public.payroll_runs
    ADD CONSTRAINT fk_payroll_runs_location FOREIGN KEY (location_id) REFERENCES public.locations(location_id);

-- "Reports to": if the manager's record is deleted the link is cleared, the person stays.
ALTER TABLE ONLY public.employees
    ADD CONSTRAINT fk_employees_manager FOREIGN KEY (manager_id) REFERENCES public.employees(id) ON DELETE SET NULL;

-- Day-to-day records belong to one person and go with them if the person is deleted.
ALTER TABLE ONLY public.attendance_records
    ADD CONSTRAINT fk_attendance_employee FOREIGN KEY (employee_id) REFERENCES public.employees(id) ON DELETE CASCADE;
ALTER TABLE ONLY public.leave_requests
    ADD CONSTRAINT fk_leave_employee FOREIGN KEY (employee_id) REFERENCES public.employees(id) ON DELETE CASCADE;
ALTER TABLE ONLY public.on_duty_requests
    ADD CONSTRAINT fk_on_duty_employee FOREIGN KEY (employee_id) REFERENCES public.employees(id) ON DELETE CASCADE;

-- Pay history is kept: a person with payslips cannot be deleted (set them to Deactivated instead).
ALTER TABLE ONLY public.payslips
    ADD CONSTRAINT fk_payslips_employee FOREIGN KEY (employee_id) REFERENCES public.employees(id) ON DELETE RESTRICT;
-- Payslips belong to one payroll run; removing a draft run removes its payslips.
ALTER TABLE ONLY public.payslips
    ADD CONSTRAINT fk_payslips_run FOREIGN KEY (payroll_run_id) REFERENCES public.payroll_runs(id) ON DELETE CASCADE;

-- ---------------------------------------------------------------------------------------------
-- Rules
-- ---------------------------------------------------------------------------------------------

-- One attendance row per person per day (check-in and check-out update the same row).
ALTER TABLE ONLY public.attendance_records
    ADD CONSTRAINT uq_attendance_employee_date UNIQUE (employee_id, date);

-- Only three kinds of people: the owner (admin), a center manager, and staff.
ALTER TABLE public.employees
    ADD CONSTRAINT ck_employees_role CHECK (role IS NULL OR role IN ('ADMIN', 'MANAGER', 'EMPLOYEE'));

ALTER TABLE public.payroll_runs
    ADD CONSTRAINT ck_payroll_runs_status CHECK (status IS NULL OR status IN ('DRAFT', 'APPROVED', 'DISBURSED'));

