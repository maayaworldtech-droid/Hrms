-- Notifications shown under the bell in the staff portal (and mostly emailed as well).
-- One row per person per event: the unique rule is what stops an event being notified or
-- emailed twice, for example after a double click or a retried request.

CREATE TABLE public.notifications (
    id bigint NOT NULL,
    employee_id bigint NOT NULL,
    type character varying(255) NOT NULL,
    event_key character varying(255) NOT NULL,
    title character varying(255) NOT NULL,
    message text,
    link character varying(255),
    is_read boolean NOT NULL DEFAULT false,
    created_at timestamp(6) without time zone NOT NULL,
    read_at timestamp(6) without time zone,
    email_status character varying(255)
);

ALTER TABLE public.notifications ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.notifications_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.notifications
    ADD CONSTRAINT notifications_pkey PRIMARY KEY (id);

ALTER TABLE ONLY public.notifications
    ADD CONSTRAINT uq_notifications_employee_event UNIQUE (employee_id, event_key);

ALTER TABLE ONLY public.notifications
    ADD CONSTRAINT fk_notifications_employee FOREIGN KEY (employee_id) REFERENCES public.employees(id) ON DELETE CASCADE;

-- The bell asks for "my latest" and "how many unread"
CREATE INDEX idx_notifications_employee_created ON public.notifications (employee_id, created_at DESC);
CREATE INDEX idx_notifications_unread ON public.notifications (employee_id) WHERE is_read = false;
